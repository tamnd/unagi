// unicodedata is a built-in module. CPython implements it as a C extension over
// the bundled Unicode Character Database; the runtime provides the same surface
// in Go under the import name so `import unicodedata` (and the modules that
// import it, pdb through _pyrepl.utils and doctest through pdb, and stringprep
// through the ucd_3_2_0 accessor below) load.
//
// The general category, the canonical combining class, the raw decomposition
// strings, the decomposition and composition mappings that back normalize /
// is_normalized, the decimal/digit/numeric values, the Bidi_Mirrored flag, and
// the Bidi_Class ranges are all pinned from the CPython 3.14.6 UCD in
// unicodedata_tables.go (generated by gen_unicodedata_tables.py), so they agree
// with CPython character for character. unidata_version reports that same UCD
// version, so category and the reported version name the same data. The character
// name database is pinned too: name() reads the explicit names and formats the
// algorithmic Hangul and CJK-style ranges, and lookup() reverses those and also
// resolves the name aliases and named sequences, so the whole module answers from
// the one UCD.

func init() {
	moduleTable["unicodedata"] = &moduleEntry{builtin: true, exec: initUnicodedata}
	// Fill the namereplace error handler's name lookup with the pinned name
	// database, the way CPython's namereplace reaches unicodedata's getname.
	objects.NameReplaceNameLookup = charName
	// Fill str.casefold's fold map with the pinned CaseFolding.txt C+F table, so
	// the folding agrees with CPython character for character.
	objects.CaseFoldHook = caseFoldLookup
	// Fill str.upper's full uppercase map with the pinned table, so the German
	// sharp s and the ligatures expand the way CPython's str.upper does.
	objects.UpperFullHook = upperFullLookup
	// Fill str.lower's full lowercase map and the Cased/Case_Ignorable sets its
	// Final_Sigma walk consults, so the Greek capital sigma lowercases to its
	// final form word-finally the way CPython's str.lower does.
	objects.LowerFullHook = lowerFullLookup
	objects.CasedHook = casedLookup
	objects.CaseIgnorableHook = caseIgnorableLookup
	// Fill str.title and str.capitalize's full titlecase map with the pinned
	// table, so the German sharp s titlecases to Ss and the ligatures expand the
	// way CPython does.
	objects.TitleFullHook = titleFullLookup
	// Fill str.swapcase's branch predicates with the pinned Uppercase/Lowercase
	// sets, so it lowercases the uppercase characters and uppercases the lowercase
	// ones while leaving the titlecase and caseless ones the way CPython does.
	objects.UppercaseHook = uppercaseLookup
	objects.LowercaseHook = lowercaseLookup
	// Fill str.isalpha / isalnum / isdecimal / isdigit / isnumeric / isprintable's
	// classification with the pinned category and digit/numeric value tables, so
	// they answer for the newer blocks the way CPython does.
	objects.CategoryHook = runeCategory
	objects.DigitHook = func(r rune) bool { _, ok := ucdDigit[r]; return ok }
	objects.NumericHook = func(r rune) bool { _, ok := ucdNumeric[r]; return ok }
	// Fill str.isidentifier's classification with the pinned XID_Start/XID_Continue
	// sets, so an identifier made of the newer blocks is recognized the way CPython
	// does.
	objects.IDStartHook = func(r rune) bool { return inRuneRanges(ucdXidStart, r) }
	objects.IDContinueHook = func(r rune) bool { return inRuneRanges(ucdXidContinue, r) }
	// Resolve the frontend lexer's \N{NAME} string escape through the same pinned
	// name database lookup() uses, so a \N escape in a source literal names the
	// same character unicodedata.lookup would.
	frontend.NamedUnicodeLookup = func(name string) (string, bool) {
		nameOnce.Do(buildNameIndex)
		return charLookup(name)
	}
}

// caseFoldLookup returns the full case fold of a code point, or nil when the
// point folds to itself (absent from the pinned table).
func caseFoldLookup(r rune) []rune {
	return ucdCaseFold[r]
}

// upperFullLookup returns the full uppercase of a code point, or nil when the
// point uppercases to itself (absent from the pinned table).
func upperFullLookup(r rune) []rune {
	return ucdUpperFull[r]
}

// lowerFullLookup returns the full lowercase of a code point, or nil when the
// point lowercases to itself (absent from the pinned table). The Greek capital
// sigma is absent by design; its final form is chosen by the Final_Sigma walk.
func lowerFullLookup(r rune) []rune {
	return ucdLowerFull[r]
}

// titleFullLookup returns the full titlecase of a code point, or nil when the
// point titlecases to itself (absent from the pinned table).
func titleFullLookup(r rune) []rune {
	return ucdTitleFull[r]
}

// casedLookup reports whether a code point is Cased, the property str.lower's
// Final_Sigma walk consults for the letters bounding the sigma and str.title uses
// to find the first cased character of each word.
func casedLookup(r rune) bool {
	return inRuneRanges(ucdCased, r)
}

// caseIgnorableLookup reports whether a code point is Case_Ignorable, the
// characters str.lower's Final_Sigma walk skips over between cased letters.
func caseIgnorableLookup(r rune) bool {
	return inRuneRanges(ucdCaseIgnorable, r)
}

// uppercaseLookup reports whether a code point has the Uppercase property, so
// str.swapcase lowercases it.
func uppercaseLookup(r rune) bool {
	return inRuneRanges(ucdUppercase, r)
}

// lowercaseLookup reports whether a code point has the Lowercase property, so
// str.swapcase uppercases it.
func lowercaseLookup(r rune) bool {
	return inRuneRanges(ucdLowercase, r)
}

// inRuneRanges reports whether r falls in one of the sorted, inclusive ranges by
// binary search.
func inRuneRanges(ranges [][2]rune, r rune) bool {
	lo, hi := 0, len(ranges)
	for lo < hi {
		mid := (lo + hi) / 2
		switch {
		case r < ranges[mid][0]:
			hi = mid
		case r > ranges[mid][1]:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

func initUnicodedata(m *objects.Module) error {
	names := []string{
		"category", "combining", "east_asian_width", "bidirectional",
		"mirrored", "decomposition", "decimal", "digit", "numeric",
		"name", "lookup", "normalize", "is_normalized",
	}
	vals := []objects.Object{
		objects.NewFunc("category", 1, udCategory),
		objects.NewFunc("combining", 1, udCombining),
		objects.NewFunc("east_asian_width", 1, udEastAsianWidth),
		objects.NewFunc("bidirectional", 1, udBidirectional),
		objects.NewFunc("mirrored", 1, udMirrored),
		objects.NewFunc("decomposition", 1, udDecomposition),
		objects.NewFuncKw("decimal", udDecimal),
		objects.NewFuncKw("digit", udDigit),
		objects.NewFuncKw("numeric", udNumeric),
		objects.NewFuncKw("name", udName),
		objects.NewFunc("lookup", 1, udLookup),
		objects.NewFunc("normalize", 2, udNormalize),
		objects.NewFunc("is_normalized", 2, udIsNormalized),
	}
	for i, name := range names {
		if err := objects.StoreAttr(m, name, vals[i]); err != nil {
			return err
		}
	}
	if err := objects.StoreAttr(m, "unidata_version", objects.NewStr(ucdVersion)); err != nil {
		return err
	}

	// ucd_3_2_0 is CPython's accessor for the UCD frozen at Unicode 3.2.0, the
	// version RFC 3454 (stringprep) is written against; stringprep.py binds it as
	// its `unicodedata` and asserts `unidata_version == '3.2.0'` at import. It is
	// modeled here as a namespace over the same function set as the module (a
	// SimpleNamespace calls a stored function unbound, so `ucd_3_2_0.category(c)`
	// has the same one-argument shape), so the category-driven stringprep tables
	// answer correctly and the properties Go's stdlib does not carry keep the same
	// documented best-effort behavior as the module. Its unidata_version reports
	// '3.2.0', matching CPython byte for byte, since that is the identity of this
	// accessor rather than a claim about the data behind it.
	nsNames := append(append([]string{}, names...), "unidata_version")
	nsVals := append(append([]objects.Object{}, vals...), objects.NewStr("3.2.0"))
	ucd320 := objects.NewSimpleNamespace(nsNames, nsVals)
	return objects.StoreAttr(m, "ucd_3_2_0", ucd320)
}

// oneRune pulls the single code point an argument must be, matching the C
// module's "need a single Unicode character" TypeError.
func oneRune(fn string, o objects.Object) (rune, error) {
	s, ok := objects.AsStr(o)
	if !ok {
		return 0, objects.Raise(objects.TypeError,
			"%s() argument 1 must be a unicode character, not %s", fn, o.TypeName())
	}
	// StrRunes decodes WTF-8 so a lone surrogate stays one code point; []rune
	// would split its three bytes into three U+FFFD runes and wrongly fail the
	// single-character check. CPython accepts any single code point here.
	runes := objects.StrRunes(s)
	if len(runes) != 1 {
		return 0, objects.Raise(objects.TypeError,
			"%s() argument 1 must be a unicode character, not str", fn)
	}
	return runes[0], nil
}

// categoryRange is one [lo, hi] run of code points that share a general
// category, the shape ucdCategoryRanges in unicodedata_tables.go is generated as.
// The ranges are sorted by lo and do not overlap, so a code point's category is
// found by binary search.
type categoryRange struct {
	lo, hi rune
	class  string
}

// runeCategory returns the CPython general category code from the pinned range
// table, "Cn" for a code point in no stored range (an unassigned one).
func runeCategory(r rune) string {
	lo, hi := 0, len(ucdCategoryRanges)
	for lo < hi {
		mid := (lo + hi) / 2
		cr := ucdCategoryRanges[mid]
		switch {
		case r < cr.lo:
			hi = mid
		case r > cr.hi:
			lo = mid + 1
		default:
			return cr.class
		}
	}
	return "Cn"
}

// udCategory is unicodedata.category(chr), read from the pinned UCD so it matches
// CPython 3.14 rather than the older UCD Go's `unicode` package tracks.
func udCategory(args []objects.Object) (objects.Object, error) {
	r, err := oneRune("category", args[0])
	if err != nil {
		return nil, err
	}
	return objects.NewStr(runeCategory(r)), nil
}

// udCombining is unicodedata.combining(chr), the canonical combining class,
// read from the pinned UCD table. A character with no entry has class 0, its
// true value.
func udCombining(args []objects.Object) (objects.Object, error) {
	r, err := oneRune("combining", args[0])
	if err != nil {
		return nil, err
	}
	return objects.NewInt(int64(ucdCombiningClass[r])), nil
}

// eawRange is one [lo, hi] run of code points that share an East_Asian_Width
