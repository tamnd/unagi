import math,sys
def show(label, fn):
    try: print(label, "=>", repr(fn())[:30])
    except Exception as e: print(label, "=>", type(e).__name__, ":", e)
big = 10**(sys.float_info.max_10_exp+5)
show("sqrt(big)", lambda: math.sqrt(big))
show("hypot(1,big)", lambda: math.hypot(1,big))
show("hypot(big,1)", lambda: math.hypot(big,1))
show("dist((1,big),(2,3))", lambda: math.dist((1,big),(2,3)))
show("dist((2,3),(1,big))", lambda: math.dist((2,3),(1,big)))
show("fsum([10**1000])", lambda: math.fsum([10**1000]))
show("fsum([1e308,1e308])", lambda: math.fsum([1e308,1e308]))
show("sin(big)", lambda: math.sin(big))
show("log(big)", lambda: math.log(big))
show("hypot(3,4)", lambda: math.hypot(3,4))
show("sqrt(4)", lambda: math.sqrt(4))
show("hypot(inf,1)", lambda: math.hypot(float('inf'),1))
show("sqrt(inf)", lambda: math.sqrt(float('inf')))
show("fsum([1.0,2.0])", lambda: math.fsum([1.0,2.0]))
show("sqrt(nan)", lambda: math.sqrt(float('nan')))
